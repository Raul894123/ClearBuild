_GEOCODE_CACHE: Dict[str, Tuple[List[float], Dict[str, int], str]] = {}


def geocode_address(address: Optional[str]) -> List[float]:
    """Возвращает верифицированные координаты [lat, lng] OpenStreetMap для адреса в г. Усть-Каменогорск (офлайн-словарь)."""
    if not address or not isinstance(address, str):
        return list(DEFAULT_UKG_COORDS)
    
    clean_addr = address.strip()
    if not clean_addr:
        return list(DEFAULT_UKG_COORDS)

    for pattern, coords, _ in STREET_GEOCODE_RULES:
        if pattern.search(clean_addr):
            return list(coords)

    return list(DEFAULT_UKG_COORDS)


def svg_pos_from_coords(coords: Optional[List[float]], address: Optional[str] = None) -> Dict[str, int]:
    """Возвращает координаты {x, y} для нанесения на SVG офлайн-карту Усть-Каменогорска."""
    if address:
        clean_addr = address.strip()
        for pattern, _, svg_pos in STREET_GEOCODE_RULES:
            if pattern.search(clean_addr):
                return dict(svg_pos)

    if not coords or len(coords) < 2:
        return dict(DEFAULT_UKG_SVG_POS)

    lat, lng = coords[0], coords[1]
    
    # Линейная интерполяция в рамку векторной схемы Усть-Каменогорска
    # Bounding box: lat 49.88..50.04 -> y 440..90, lng 82.56..82.74 -> x 170..700
    try:
        lat_ratio = max(0.0, min(1.0, (lat - 49.88) / (50.04 - 49.88)))
        lng_ratio = max(0.0, min(1.0, (lng - 82.56) / (82.74 - 82.56)))
        y = int(440 - lat_ratio * 350)
        x = int(170 + lng_ratio * 530)
        return {"x": max(100, min(750, x)), "y": max(60, min(480, y))}
    except Exception:
        return dict(DEFAULT_UKG_SVG_POS)


def geocode_address_online(address: Optional[str], timeout: float = 2.5) -> Tuple[List[float], Dict[str, int], str]:
    """Геокодирует адрес через OpenStreetMap Nominatim с автоматическим фоллбэком на локальную базу г. Усть-Каменогорска."""
    if not address or not isinstance(address, str) or not address.strip():
        return list(DEFAULT_UKG_COORDS), dict(DEFAULT_UKG_SVG_POS), "default"

    clean = address.strip()
    cache_key = clean.lower()
    if cache_key in _GEOCODE_CACHE:
        return _GEOCODE_CACHE[cache_key]

    # 1. Попытка запроса к живому OpenStreetMap Nominatim
    search_query = clean
    if not re.search(r"(усть-каменогорск|өскемен|вко)", search_query, re.I):
        search_query = f"Усть-Каменогорск, {search_query}"

    try:
        encoded_q = urllib.parse.quote(search_query)
        url = f"https://nominatim.openstreetmap.org/search?q={encoded_q}&format=json&limit=1&countrycodes=kz"
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "ClearBuild-Hackathon-App/1.0 (contact@komputerny-oslik.site)"}
        )
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            if resp.status == 200:
                data = json.loads(resp.read().decode("utf-8"))
                if data and isinstance(data, list) and len(data) > 0:
                    lat = float(data[0]["lat"])
                    lng = float(data[0]["lon"])
                    # Границы Усть-Каменогорска и окрестностей
                    if 49.80 <= lat <= 50.15 and 82.40 <= lng <= 82.90:
                        coords = [round(lat, 5), round(lng, 5)]
                        svg_pos = svg_pos_from_coords(coords, clean)
                        result = (coords, svg_pos, "osm_nominatim")
                        _GEOCODE_CACHE[cache_key] = result
                        return result
    except Exception:
        # При таймауте, блокировке или отсутствии интернета безопасно переходим к офлайн-словарю
        pass

    # 2. Офлайн-геокодер по проверенным правилам Усть-Каменогорска
    coords = geocode_address(clean)
    svg_pos = svg_pos_from_coords(coords, clean)
    source = "offline_dictionary" if (coords != DEFAULT_UKG_COORDS) else "default"
    result = (coords, svg_pos, source)
    _GEOCODE_CACHE[cache_key] = result
    return result
